/**
 * public/og/index.json → lib/og-thumbs.generated.ts
 *
 * THUMBNAIL_STANDARD 7장: og 인덱스가 썸네일 경로의 유일한 출처다.
 * 워커 런타임에는 파일시스템이 없으므로 빌드 전에 정적 모듈로 구워 둔다.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const INDEX = join(ROOT, 'public/og/index.json')
const idx = existsSync(INDEX) ? JSON.parse(readFileSync(INDEX, 'utf8')).items ?? {} : {}
const items = Object.keys(idx)
// ?v=<이미지 해시 앞 8자> — 같은 파일명으로 다시 구운 카드(WQA1021-FIX2 zh·ja □ 재생성)를
// CF 엣지·SNS 가 옛 바이트로 계속 주는 것을 막는다(/og/* 는 max-age 1일 + swr 7일).
const ver = Object.fromEntries(items.sort().map((k) => [k, (idx[k].hash || '').slice(0, 8)]))

const out = `// AUTO-GENERATED by scripts/build-og-thumbs.mjs — 손으로 고치지 않는다.
const OG_VER: Record<string, string> = ${JSON.stringify(ver, null, 0)}
const v = (k: string) => (OG_VER[k] ? \`?v=\${OG_VER[k]}\` : '')

/**
 * 글별 고유 OG 썸네일.
 * 번역본이 없는 언어 페이지는 한국어 제목·본문을 그대로 보여주므로 이미지도 같다
 * (같은 문장으로 그리면 해시가 같아 THUMBNAIL_STANDARD 6장 중복 게이트에 걸린다).
 * 그런 페이지는 ko 판을 가리킨다 — 없는 이미지를 지어내지 않는다.
 * ko 판마저 없으면 빈 문자열 → 빌드 게이트가 잡는다(조용한 대체 금지).
 */
export function ogThumb(locale: string, slug: string): string {
  if (\`\${locale}/\${slug}\` in OG_VER) return \`/og/\${locale}/\${slug}.png\${v(\`\${locale}/\${slug}\`)}\`
  if (\`ko/\${slug}\` in OG_VER) return \`/og/ko/\${slug}.png\${v(\`ko/\${slug}\`)}\`
  return ''
}

/** 목록 카드용 800×450 재렌더판. */
export function ogCard(locale: string, slug: string): string {
  const p = ogThumb(locale, slug)
  return p ? p.replace(/\\.png(\\?|$)/, '-card.png$1') : ''
}

export const OG_COUNT = ${items.length}
`
writeFileSync(join(ROOT, 'lib/og-thumbs.generated.ts'), out)
console.log(`lib/og-thumbs.generated.ts: ${items.length} keys`)
