/**
 * lib/services-catalog.ts + lib/industry-pages.ts → lib/sitemap-index.generated.ts
 *
 * INHEGA-FOCUS-1103 A(맥7 승인 11-03): 사이트맵 라우트가 slug 목록만 쓰면서 서비스 본문 정본(services-data·services-i18n)과
 * 업종 원고 JSON 전체를 import 해, 라우트 핸들러 레이어에 본문 사본(약 2.6MB)이 한 벌 더 실렸다(워커 25 MiB 한도).
 * 사이트맵이 쓰는 값(언어별 서비스·업종 slug)만 구워 둔다 — 값은 정본 함수를 실행해서 받는다. prebuild 마다 다시 만든다.
 */
import { register } from 'node:module'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
register(pathToFileURL(join(ROOT, 'scripts/lib/ts-esm-loader.mjs')).href, pathToFileURL(ROOT + '/'))

const { getServiceSlugs } = await import(pathToFileURL(join(ROOT, 'lib/services-catalog.ts')).href)
const { getIndustrySlugs } = await import(pathToFileURL(join(ROOT, 'lib/industry-pages.ts')).href)

const L = ['ko', 'en', 'zh', 'ja']
const services = Object.fromEntries(L.map((l) => [l, getServiceSlugs(l)]))
const industry = Object.fromEntries(L.map((l) => [l, getIndustrySlugs(l)]))

const OUT = join(ROOT, 'lib/sitemap-index.generated.ts')
const body = `// AUTO-GENERATED by scripts/build-sitemap-index.mjs — 손으로 고치지 않는다(정본: lib/services-catalog.ts, lib/industry-pages.ts).
// 사이트맵 전용 경량 색인(언어별 slug 만). 본문은 싣지 않는다.
type L = 'ko' | 'en' | 'zh' | 'ja'

export const SITEMAP_SERVICE_SLUGS: Record<L, string[]> = ${JSON.stringify(services)}

export const SITEMAP_INDUSTRY_SLUGS: Record<L, string[]> = ${JSON.stringify(industry)}
`
const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (prev !== body) writeFileSync(OUT, body)
console.log(`[sitemap-index] 서비스 ${L.map((l) => `${l} ${services[l].length}`).join(' · ')} / 업종 ${L.map((l) => `${l} ${industry[l].length}`).join(' · ')}${prev === body ? ' (변경 없음)' : ' → lib/sitemap-index.generated.ts'}`)
