/**
 * lib/blog-posts-data.ts + lib/i18n/blog-i18n.ts → lib/blog-feed-index.generated.ts
 *
 * INHEGA-FOCUS-1103(2026-11-03): 사이트맵·RSS 라우트가 블로그 본문 정본 두 개를 통째로 import 해서
 * 라우트 핸들러 레이어에 본문 사본(약 8MB)이 한 벌 더 실렸고, 워커가 CF 한도 25 MiB 를 넘어
 * 11-01 저녁부터 배포가 거부됐다(code 8000101). 두 라우트가 쓰는 필드만 구워 둔다 — 값은 정본 그대로.
 * 정본에서 고칠 것. 이 파일은 prebuild 마다 다시 만든다.
 */
import { register } from 'node:module'
import { pathToFileURL, fileURLToPath } from 'node:url'
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { join, dirname } from 'node:path'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
register(pathToFileURL(join(ROOT, 'scripts/lib/ts-esm-loader.mjs')).href, pathToFileURL(ROOT + '/'))

const { blogPosts } = await import(pathToFileURL(join(ROOT, 'lib/blog-posts-data.ts')).href)
const i18n = await import(pathToFileURL(join(ROOT, 'lib/i18n/blog-i18n.ts')).href)

const ko = blogPosts.map((p) => ({
  slug: p.slug, title: p.title, excerpt: p.excerpt, meta_description: p.meta_description,
  created_at: p.created_at, ...(p.updated_at ? { updated_at: p.updated_at } : {}),
}))
const tr = ['en', 'zh', 'ja'].flatMap((l) => i18n.getAllTranslatedSlugs(l).map((s) => {
  const t = i18n.getBlogI18n(l, s)
  return { locale: l, slug: s, title: t.title, excerpt: t.excerpt, metaDescription: t.metaDescription }
}))

const OUT = join(ROOT, 'lib/blog-feed-index.generated.ts')
const body = `// AUTO-GENERATED by scripts/build-blog-feed-index.mjs — 손으로 고치지 않는다(정본: lib/blog-posts-data.ts, lib/i18n/blog-i18n.ts).
// 사이트맵·RSS 전용 경량 색인. 본문(content)은 싣지 않는다.
export interface FeedPostKo { slug: string; title: string; excerpt: string; meta_description: string; created_at: string; updated_at?: string }
export interface FeedPostI18n { locale: 'en' | 'zh' | 'ja'; slug: string; title: string; excerpt: string; metaDescription: string }

export const FEED_POSTS_KO: FeedPostKo[] = ${JSON.stringify(ko, null, 0)}

export const FEED_POSTS_I18N: FeedPostI18n[] = ${JSON.stringify(tr, null, 0)}

export function getFeedTranslatedSlugs(locale: 'en' | 'zh' | 'ja'): string[] {
  return FEED_POSTS_I18N.filter((p) => p.locale === locale).map((p) => p.slug)
}

export function getFeedI18n(locale: 'en' | 'zh' | 'ja', slug: string): FeedPostI18n | null {
  return FEED_POSTS_I18N.find((p) => p.locale === locale && p.slug === slug) ?? null
}
`
// INHEGA-QA1102-FIX A-3(맥7 승인): 블로그 목록 4개도 본문 정본을 import 하지 않게 목록 전용 색인을 같이 굽는다.
// 상세 페이지는 빌드 시 정적 HTML 로만 내보내고(scripts/blog-static-extract.mjs) 워커 번들에서 본문을 뺀다.
const koById = new Map(blogPosts.map((p) => [p.slug, p]))
const listKo = blogPosts.map((p) => ({
  id: p.id, slug: p.slug, title: p.title, category: p.category ?? '',
  excerpt: p.excerpt || (p.content || '').substring(0, 80), created_at: p.created_at,
}))
const listI18n = ['en', 'zh', 'ja'].flatMap((l) => i18n.getAllTranslatedSlugs(l).map((s) => {
  const t = i18n.getBlogI18n(l, s)
  return { locale: l, slug: s, title: t.title, category: t.category ?? '', excerpt: t.excerpt, created_at: koById.get(s)?.created_at ?? '' }
}))
const LIST_OUT = join(ROOT, 'lib/blog-list-index.generated.ts')
const listBody = `// AUTO-GENERATED by scripts/build-blog-feed-index.mjs — 손으로 고치지 않는다(정본: lib/blog-posts-data.ts, lib/i18n/blog-i18n.ts).
// 블로그 목록 전용 경량 색인(INHEGA-QA1102-FIX A-3). 본문(content)은 싣지 않는다.
export interface ListPostKo { id: string | number; slug: string; title: string; category: string; excerpt: string; created_at: string }
export interface ListPostI18n { locale: 'en' | 'zh' | 'ja'; slug: string; title: string; category: string; excerpt: string; created_at: string }

export const LIST_POSTS_KO: ListPostKo[] = ${JSON.stringify(listKo, null, 0)}

export const LIST_POSTS_I18N: ListPostI18n[] = ${JSON.stringify(listI18n, null, 0)}
`
const listPrev = existsSync(LIST_OUT) ? readFileSync(LIST_OUT, 'utf8') : ''
if (listPrev !== listBody) writeFileSync(LIST_OUT, listBody)

const prev = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
if (prev !== body) writeFileSync(OUT, body)
console.log(`[blog-feed-index] ko ${ko.length} · en/zh/ja ${tr.length} · ${(body.length / 1024).toFixed(0)}KB`)
